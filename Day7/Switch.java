package Day7;

public class Switch {
    public static void main(String[] args) {
        int input = 2;

        switch (input) {
            case 1:
                System.out.println("Samosa");
                break;
            
            case 2:
                System.out.println("Mango Shake");
                break;
            
            case 3:
                System.out.println("Fruit");
                break;
            
            default:
                System.out.println("Not Found");
                break;
            
        }
    }
}
